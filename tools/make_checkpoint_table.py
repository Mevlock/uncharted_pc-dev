"""make_checkpoint_table.py <checkpoints_all_games.txt> <out .inc>: the checkpoint list (every task of the three
games in game order, as the saves' progress tables hold them) as a C table for the overlay: game, task id,
playable number (0 = a cutscene, AI setup or system entry), chapter number, chapter title, the task's name."""
import re, sys
rows, game = [], 0
line_re = re.compile(r'^\s*(#\d+|-)\s+ch\s*(\d+) (.{32}) (.*?)\s*row\s+(\d+)\s+([0-9a-f]{8})\s*$')
for line in open(sys.argv[1], encoding='utf-8'):
    if line.startswith('===== Uncharted '):
        game = int(line[16])
        continue
    m = line_re.match(line.rstrip('\n'))
    if not m or not game:
        continue
    num, ch, title, name, row, tid = m.groups()
    rows.append((game, int(tid, 16), 0 if num == '-' else int(num[1:]), int(ch), title.strip(), name.strip()))
counts = {g: sum(1 for r in rows if r[0] == g) for g in (1, 2, 3)}
assert all(counts.values()), counts


def c(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as out:
    out.write('// Generated by tools/make_checkpoint_table.py: {game, task id, checkpoint number (0: not a start point), '
              'chapter, chapter title, task name}\n')
    for g, tid, num, ch, title, name in rows:
        out.write(f'{{{g}, 0x{tid:08x}u, {num}, {ch}, {c(title)}, {c(name)}}},\n')
print(counts, {g: max(r[2] for r in rows if r[0] == g) for g in (1, 2, 3)})
