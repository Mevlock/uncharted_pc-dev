#!/usr/bin/env python3
"""The in-game menu's translations: gpu/shim/overlay_i18n.py (the one place they are edited) written to
gpu/shim/bbport_overlay_i18n.inc (checked in: the build needs no Python), and checked.

    python tools/make_overlay_i18n.py           writes the .inc
    python tools/make_overlay_i18n.py --check   checks only (exit 1 on a problem): every text marked in the C++
                                                files has all six languages with the same placeholders, and the
                                                .inc is up to date
    python tools/make_overlay_i18n.py --list    prints the marked texts
    python tools/make_overlay_i18n.py --chars   prints the characters the Japanese texts use (the font subset)

Marked texts: string literals (adjacent ones joined) in T("..."), TI("..."), N_("...") and tr("...") in SOURCES.
"""
import argparse
import ast
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHIM = ROOT / 'gpu' / 'shim'
SOURCES = [SHIM / 'bbport_overlay.cpp', SHIM / 'bbport_saves.cpp']
DATA = SHIM / 'overlay_i18n.py'
OUTPUT = SHIM / 'bbport_overlay_i18n.inc'
LANGUAGES = ('es', 'pt', 'fr', 'de', 'it', 'ja')  # the order bbport_i18n.cpp reads

MARK = re.compile(r'\b(?:T|TI|N_|tr)\(\s*(?=")')
LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"\s*')
# printf conversions (and %%, a literal %) and fmt fields
PRINTF = re.compile(r'%%|%[-+#0]*\d*(?:\.\d+)?[hlLzjt]*[diouxXeEfgGcsp]')
FMT = re.compile(r'\{[^{}]*\}')


def unescape(text):
    """A C string literal's body as text (UTF-8, \\xHH bytes, the usual escapes)."""
    out = bytearray()
    i = 0
    raw = text.encode('utf-8')
    simple = {ord('n'): 10, ord('t'): 9, ord('"'): 34, ord('\\'): 92, ord("'"): 39, ord('0'): 0}
    while i < len(raw):
        c = raw[i]
        if c == 92 and i + 1 < len(raw):
            n = raw[i + 1]
            if n == ord('x'):
                j = i + 2
                while j < len(raw) and chr(raw[j]) in '0123456789abcdefABCDEF':
                    j += 1
                out.append(int(raw[i + 2:j], 16) & 0xff)
                i = j
                continue
            out.append(simple.get(n, n))
            i += 2
            continue
        out.append(c)
        i += 1
    return out.decode('utf-8')


def marked_texts(paths=SOURCES):
    """{text: 'file:line'} for every marked literal."""
    found = {}
    for path in paths:
        source = path.read_text(encoding='utf-8')
        for match in MARK.finditer(source):
            at = match.end()
            parts = []
            while (lit := LITERAL.match(source, at)):
                parts.append(unescape(lit.group(1)))
                at = lit.end()
            if not parts or source[at] not in '),':
                continue
            text = ''.join(parts)
            found.setdefault(text, f'{path.name}:{source.count(chr(10), 0, match.start()) + 1}')
    return found


def load_data():
    spec = importlib.util.spec_from_file_location('overlay_i18n', DATA)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.TRANSLATIONS


def placeholders(text):
    return PRINTF.findall(text), FMT.findall(text)


def problems(found, data):
    out = []
    for text, where in found.items():
        row = data.get(text)
        if row is None:
            out.append(f'{where}: no translations for {text!r}')
            continue
        for lang in LANGUAGES:
            if not row.get(lang):
                out.append(f'{where}: no {lang} for {text!r}')
    for text, row in data.items():
        for lang, translated in row.items():
            if lang not in LANGUAGES:
                out.append(f'unknown language {lang!r} for {text!r}')
            elif translated and placeholders(translated) != placeholders(text):
                out.append(f'{lang}: placeholders differ from the English in {text!r}: {translated!r}')
    return out


def c_string(text):
    out = ''
    for ch in text:
        out += {'"': '\\"', '\\': '\\\\', '\n': '\\n'}.get(ch, ch)
    return '"' + out + '"'


def render(data):
    lines = ['// Generated by tools/make_overlay_i18n.py from gpu/shim/overlay_i18n.py: edit that file, then run the',
             '// tool. {English, ' + ', '.join(LANGUAGES) + '}; "" = not translated (English is shown).']
    for text in sorted(data):
        row = data[text]
        cells = [c_string(text)] + [c_string(row.get(lang, '')) for lang in LANGUAGES]
        lines.append('{' + cells[0] + ', {' + ', '.join(cells[1:]) + '}},')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--list', action='store_true')
    parser.add_argument('--chars', action='store_true')
    args = parser.parse_args()
    found = marked_texts()
    if args.list:
        for text, where in found.items():
            print(f'{where}\t{text}')
        return 0
    data = load_data()
    if args.chars:
        print(''.join(sorted({ch for row in data.values() for ch in row.get('ja', '')})))
        return 0
    issues = problems(found, data)
    text = render(data)
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != text:
            issues.append(f'{OUTPUT.name} is out of date: run tools/make_overlay_i18n.py')
        for issue in issues:
            print(issue)
        return 1 if issues else 0
    for issue in issues:
        print('warning:', issue)
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'{OUTPUT.name}: {len(data)} texts ({len(found)} marked in the C++ files)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
