"""Builds gpu/shadps4/video_core/texture_cache/button_prompts_xbox.inc: the Xbox button pictures the
button prompts draw on the games' icon sheets (button_prompts.cpp).

The pictures are drawn by tools/xbox_prompts_domed.py (dark domed buttons, close to the games' own
button art):

    python tools/make_xbox_prompts.py [--preview atlas.png]

or, with --kenney, Kenney's flat "Input Prompts" (CC0, https://kenney.nl/assets/input-prompts), Xbox
Series, the 128 px "Double" PNGs (the pictures before 0.3.6.13's release):

    python tools/make_xbox_prompts.py --kenney <folder holding "Xbox Series"> [--preview atlas.png]

Output: one zlib-compressed RGBA atlas (6 columns of 128x128 cells) and the name table, as C++.
Needs Pillow; the build does not (the .inc is checked in).
"""
import argparse
import sys
import zlib
from pathlib import Path

from PIL import Image

CELL = 128
COLUMNS = 6
# Names are the file names without "xbox_" and ".png", in the order button_prompts.cpp uses them.
GLYPHS = [
    "button_color_a", "button_color_b", "button_color_x", "button_color_y",
    "lb", "rb", "lt", "rt",
    "stick_l_press", "stick_r_press", "stick_l", "stick_r",
    "button_menu", "button_view",
    "dpad", "dpad_up", "dpad_down", "dpad_horizontal", "dpad_vertical", "dpad_left", "dpad_right",
]
OUT = Path(__file__).resolve().parent.parent / "gpu/shadps4/video_core/texture_cache/button_prompts_xbox.inc"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--kenney", type=Path, metavar="PACK",
                        help="Kenney's pack instead: the folder that holds 'Xbox Series'")
    parser.add_argument("--preview", type=Path, help="also write the atlas as a PNG")
    args = parser.parse_args()
    if args.kenney:
        source = args.kenney / "Xbox Series" / "Double"
        if not source.is_dir():
            sys.exit(f"no {source}")

        def picture(name):
            return Image.open(source / f"xbox_{name}.png").convert("RGBA")
        origin = "Kenney's Input Prompts (CC0, kenney.nl), Xbox Series"
    else:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import xbox_prompts_domed
        picture = xbox_prompts_domed.draw
        origin = "tools/xbox_prompts_domed.py (Liberation Sans Bold, SIL OFL 1.1)"
    rows = (len(GLYPHS) + COLUMNS - 1) // COLUMNS
    atlas = Image.new("RGBA", (COLUMNS * CELL, rows * CELL), (0, 0, 0, 0))
    table = []
    for i, name in enumerate(GLYPHS):
        image = picture(name)
        if image.size != (CELL, CELL):
            sys.exit(f"{name}: {image.size}, expected {CELL}x{CELL}")
        x, y = (i % COLUMNS) * CELL, (i // COLUMNS) * CELL
        atlas.paste(image, (x, y))
        table.append((name, x, y))
    if args.preview:
        atlas.save(args.preview)
    packed = zlib.compress(atlas.tobytes(), 9)
    lines = [
        f"// Generated by tools/make_xbox_prompts.py from {origin}.",
        "// Do not edit. A zlib stream of the RGBA8 atlas, then the glyphs in it.",
        f"constexpr u32 xbox_atlas_width = {atlas.width}, xbox_atlas_height = {atlas.height};",
        f"constexpr u32 xbox_atlas_size = {len(packed)};",
        "constexpr u8 xbox_atlas_z[] = {",
    ]
    for start in range(0, len(packed), 24):
        lines.append("    " + ",".join(str(b) for b in packed[start:start + 24]) + ",")
    lines += ["};", "struct XboxGlyphRect {", "    const char* name;", "    u16 x, y;", "};",
              "constexpr XboxGlyphRect xbox_glyphs[] = {"]
    lines += [f'    {{"{name}", {x}, {y}}},' for name, x, y in table]
    lines += ["};", f"constexpr u32 xbox_glyph_size = {CELL};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(table)} glyphs, atlas {atlas.width}x{atlas.height}, {len(packed)} bytes compressed")


if __name__ == "__main__":
    main()
