bool PaintAtlas(uint8_t* rgba) {
    if (!Font()) {
        return false;
    }
    const Canvas& canvas = AtlasCanvas();
    for (int i = 0; i < Size * Size; ++i) {
        if (!canvas.drawn[i]) {
            continue;
        }
        const float* t = &canvas.texels[size_t(i) * 4];
        const float a = t[3];
        // Transparent texels take the glow colour: filtering at the edges blends towards it.
        const Rgb c = a > 1e-4f ? Rgb{t[0] / a, t[1] / a, t[2] / a} : glow;
        const auto byte = [](float v) { return u8(std::clamp(v * 255.0f + 0.5f, 0.0f, 255.0f)); };
        u8* o = &rgba[size_t(i) * 4];
        o[0] = byte(c.r), o[1] = byte(c.g), o[2] = byte(c.b), o[3] = byte(a);
    }
    return true;
}

namespace {
bool Redraw(uint8_t* rgba, int w, int h, bool upside_down, const std::string& label, bool face) {
    if (!Font() || w <= 0 || h <= 0) {
        return false;
    }
    Picture pic{w, h, std::vector<u8>(rgba, rgba + size_t(w) * size_t(h) * 4)};
    if (upside_down) {
        FlipRows(pic);
    }
    if (!(face ? RedrawFace(pic, label, true) : RedrawShoulder(pic, label))) {
        return false;
    }
    if (upside_down) {
        FlipRows(pic);
    }
    std::memcpy(rgba, pic.rgba.data(), pic.rgba.size());
    return true;
}
} // namespace

bool RedrawFacePicture(uint8_t* rgba, int w, int h, bool upside_down, const char* label) {
    return Redraw(rgba, w, h, upside_down, label, true);
}

bool RedrawShoulderPicture(uint8_t* rgba, int w, int h, bool upside_down, const char* label) {
    return Redraw(rgba, w, h, upside_down, label, false);
}

